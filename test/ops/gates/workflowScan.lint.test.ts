// Split provenance: test/ops/gates/workflowScan.test.ts was split by subject
// into workflowScan.{scan,reject,differential,privilege,producers,lint,headCheckout,diff,repo}.test.ts.
// This file covers the lintWorkflow rules of ADR-0004 D-G.3.
import { describe, expect, test } from 'vitest';
import { lintReasons, wf } from './workflowScan.helpers.js';

describe('lintWorkflow (ADR-0004 D-G.3)', () => {
  test.each<[string, string, number]>([
    [
      '1: pull_request_target with environment',
      wf(
        'on: pull_request_target',
        'permissions: {}',
        'jobs:',
        '  a:',
        '    environment: prod',
        '    runs-on: x',
      ),
      1,
    ],
    [
      '1: pull_request_target with a secret',
      wf(
        'on: [pull_request_target]',
        'permissions: {}',
        'jobs:',
        '  a:',
        '    runs-on: x',
        '    steps:',
        '      - run: echo ${{ secrets.K }}',
      ),
      1,
    ],
    [
      '1: not for pull_request',
      wf(
        'on: pull_request',
        'permissions: {}',
        'jobs:',
        '  a:',
        '    environment: prod',
        '    runs-on: x',
      ),
      0,
    ],
    [
      '1: GITHUB_TOKEN is fine',
      wf(
        'on: pull_request_target',
        'permissions: {}',
        'jobs:',
        '  a:',
        '    runs-on: x',
        '    steps:',
        '      - run: echo ${{ secrets.GITHUB_TOKEN }}',
      ),
      0,
    ],
    ...[
      'head_sha',
      'github.head_ref',
      'pull_request.head.sha',
      'refs/pull/1/merge',
      'merge_commit_sha',
      'workflow_run.head_branch',
    ].map((ref): [string, string, number] => [
      `2: workflow_run checkout of ${ref}`,
      wf(
        'on:',
        '  workflow_run:',
        '    workflows: [ci]',
        'permissions: {}',
        'jobs:',
        '  a:',
        '    runs-on: x',
        '    steps:',
        '      - name: co',
        '        uses: actions/checkout@v5',
        '        with:',
        `          ref: \${{ github.event.${ref} }}`,
      ),
      1,
    ]),
    [
      '2: pull_request_target quoted-uses checkout',
      wf(
        'on: pull_request_target',
        'permissions: {}',
        'jobs:',
        '  a:',
        '    runs-on: x',
        '    steps:',
        "      - uses: 'actions/checkout@v5'",
        '        with:',
        '          ref: "${{ github.event.pull_request.head.ref }}"',
      ),
      1,
    ],
    [
      '2: trust-ref checkout is fine',
      wf(
        'on: workflow_run',
        'permissions: {}',
        'jobs:',
        '  a:',
        '    runs-on: x',
        '    steps:',
        '      - uses: actions/checkout@v5',
        '        with:',
        '          ref: ${{ github.sha }}',
      ),
      0,
    ],
    [
      '2: head ref on another action is fine',
      wf(
        'on: workflow_run',
        'permissions: {}',
        'jobs:',
        '  a:',
        '    runs-on: x',
        '    steps:',
        '      - uses: some/action@v1',
        '        with:',
        '          ref: ${{ github.head_ref }}',
      ),
      0,
    ],
    [
      '2: not for pull_request',
      wf(
        'on: pull_request',
        'permissions: {}',
        'jobs:',
        '  a:',
        '    runs-on: x',
        '    steps:',
        '      - uses: actions/checkout@v5',
        '        with:',
        '          ref: ${{ github.head_ref }}',
      ),
      0,
    ],
    [
      '3: persist-credentials true with run steps',
      wf(
        'on: push',
        'permissions: {}',
        'jobs:',
        '  a:',
        '    runs-on: x',
        '    steps:',
        '      - uses: actions/checkout@v5',
        '        with:',
        '          persist-credentials: true',
        '      - run: make',
      ),
      1,
    ],
    [
      '3: quoted true',
      wf(
        'on: push',
        'permissions: {}',
        'jobs:',
        '  a:',
        '    runs-on: x',
        '    steps:',
        '      - uses: actions/checkout@v5',
        '        with:',
        "          persist-credentials: 'true'",
        '      - run: make',
      ),
      1,
    ],
    [
      '3: no run steps',
      wf(
        'on: push',
        'permissions: {}',
        'jobs:',
        '  a:',
        '    runs-on: x',
        '    steps:',
        '      - uses: actions/checkout@v5',
        '        with:',
        '          persist-credentials: true',
      ),
      0,
    ],
    [
      '3: false is fine',
      wf(
        'on: push',
        'permissions: {}',
        'jobs:',
        '  a:',
        '    runs-on: x',
        '    steps:',
        '      - uses: actions/checkout@v5',
        '        with:',
        '          persist-credentials: false',
        '      - run: make',
      ),
      0,
    ],
  ])('%s', (_label, text, count) => {
    expect(lintReasons(text)).toHaveLength(count);
  });
});
