#!/usr/bin/env node
/**
 * Generate `src/policy/crq/ledgerSchema.ts` from `policy/review-ledger.schema.json`.
 *
 * The JSON document at the repository root is the signer-validated authority
 * (owner ruling D1: `signer/` and the validator it imports stay Python). The
 * embedded copy exists so the pure TypeScript ledger contract can validate
 * without filesystem I/O; `test/policy/crq/ledger.test.ts` proves the two are
 * equal, so drift fails a test instead of silently diverging.
 *
 * Usage:
 *   node scripts/gen-crq-ledger-schema.mjs           # rewrite the module
 *   node scripts/gen-crq-ledger-schema.mjs --check   # fail when it is stale
 */
import { readFile, writeFile } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { relative, resolve } from 'node:path';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const SOURCE = resolve(ROOT, 'policy', 'review-ledger.schema.json');
const TARGET = resolve(ROOT, 'src', 'policy', 'crq', 'ledgerSchema.ts');

async function render() {
  const document = JSON.parse(await readFile(SOURCE, 'utf8'));
  return `// Generated by scripts/gen-crq-ledger-schema.mjs from policy/review-ledger.schema.json.
// Do not edit by hand; run \`node scripts/gen-crq-ledger-schema.mjs\`.
//
// This is the embedded form of the signer-validated ledger document. The
// source file remains authoritative; the drift test compares this value with
// it. Embedding keeps \`src/policy\` free of filesystem reads.
import type { JsonSchema } from './schemas.js';

export const REVIEW_LEDGER_SCHEMA: JsonSchema = ${indent(JSON.stringify(document, null, 2), '')};
`;
}

function indent(text, prefix) {
  return text.split('\n').join(`\n${prefix}`);
}

const rendered = format(await render());

/** Keep the generated module acceptable to `pnpm run format:check`. */
function format(text) {
  const result = spawnSync(
    process.execPath,
    [resolve(ROOT, 'node_modules', 'oxfmt', 'bin', 'oxfmt'), '--stdin-filepath', TARGET],
    { cwd: ROOT, input: text, encoding: 'utf8' },
  );
  if (result.error) throw result.error;
  if (result.status !== 0) {
    throw new Error(`oxfmt failed (${String(result.status)}): ${result.stderr}`);
  }
  return result.stdout;
}

if (process.argv.includes('--check')) {
  const existing = await readFile(TARGET, 'utf8').catch(() => '');
  if (existing !== rendered) {
    console.error(`${relative(ROOT, TARGET)} is stale; run node scripts/gen-crq-ledger-schema.mjs`);
    process.exit(1);
  }
} else if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  await writeFile(TARGET, rendered);
  console.error(`wrote ${relative(ROOT, TARGET)}`);
}
