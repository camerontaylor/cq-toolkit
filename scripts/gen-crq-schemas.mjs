#!/usr/bin/env node
/**
 * Generate `src/policy/crq/schemas.ts` from the phase 0.2 JSON Schemas.
 *
 * The JSON Schemas under `policy/crq/` are the authority. The generated module
 * embeds them verbatim (so the test can prove the two are identical) and hands
 * each one to `z.fromJSONSchema`, which is zod 4's draft-2020-12 converter.
 *
 * Usage:
 *   node scripts/gen-crq-schemas.mjs           # rewrite the module
 *   node scripts/gen-crq-schemas.mjs --check   # fail when it is stale
 */
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { join, relative, resolve } from 'node:path';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const SOURCE = join(ROOT, 'policy', 'crq');
const TARGET = join(ROOT, 'src', 'policy', 'crq', 'schemas.ts');

async function render() {
  const names = (await readdir(SOURCE)).filter((name) => name.endsWith('.schema.json')).sort();
  const entries = [];
  for (const name of names) {
    const text = await readFile(join(SOURCE, name), 'utf8');
    // Parse/re-serialise so the embedded literal is valid JSON in TypeScript
    // and formatting is deterministic. The test compares this parsed value
    // with the source file, not the text.
    const document = JSON.parse(text);
    entries.push(`  '${name}': ${indent(JSON.stringify(document, null, 2), '  ')},`);
  }
  return `// Generated by scripts/gen-crq-schemas.mjs from policy/crq/*.schema.json.
// Do not edit by hand; run \`node scripts/gen-crq-schemas.mjs\`.
import { z } from 'zod';

export type JsonSchema = Record<string, unknown>;

export const CRQ_STATE_SCHEMA_NAMES = [
${names.map((name) => `  '${name}',`).join('\n')}
] as const;

export type CrqStateSchemaName = (typeof CRQ_STATE_SCHEMA_NAMES)[number];

/** The phase 0.2 documents, embedded verbatim so drift is testable. */
export const crqStateSchemaDocuments: Record<CrqStateSchemaName, JsonSchema> = {
${entries.join('\n')}
};

/** zod validators derived from the phase 0.2 documents by zod's converter. */
export const crqStateSchemas = Object.fromEntries(
  CRQ_STATE_SCHEMA_NAMES.map((name) => [name, z.fromJSONSchema(crqStateSchemaDocuments[name])]),
) as unknown as Record<CrqStateSchemaName, z.ZodType>;
`;
}

function indent(text, prefix) {
  return text.split('\n').join(`\n${prefix}`);
}

const rendered = format(await render());

/**
 * The checked-in module must satisfy `format:check`. Run the repository's own
 * formatter over the generated text so a regeneration does not leave a file the
 * format gate would rewrite.
 */
function format(text) {
  const result = spawnSync(
    process.execPath,
    [resolve(ROOT, 'node_modules', 'oxfmt', 'bin', 'oxfmt'), '--stdin-filepath', TARGET],
    { cwd: ROOT, input: text, encoding: 'utf8' },
  );
  if (result.error) throw result.error;
  if (result.status !== 0) {
    throw new Error(`oxfmt failed (${String(result.status)}): ${result.stderr}`);
  }
  return result.stdout;
}

if (process.argv.includes('--check')) {
  const existing = await readFile(TARGET, 'utf8').catch(() => '');
  if (existing !== rendered) {
    console.error(`${relative(ROOT, TARGET)} is stale; run node scripts/gen-crq-schemas.mjs`);
    process.exit(1);
  }
} else if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  await writeFile(TARGET, rendered);
  console.error(`wrote ${relative(ROOT, TARGET)}`);
}
