"""Head-bound local-review associations and event-driven public presentation.

The queue transaction owns links and outbox state; gh writes are replayable by
marker. No artifact location or provider report is copied into the summary.
"""
import json
import subprocess
import time
from pathlib import Path

import local_review_runtime as runtime
import review_admission as admission
import review_operation as operation
import pr_review_findings as findings

MARKER = "<!-- crq-local-review-summary-v1 -->"


def associate(c, q, repo, pr, base, head, dry):
    if not any(i.get("kind") == operation.KIND for i in q["items"]):
        return False
    try:
        wanted = runtime.facts(c, base, head, runtime.transport.profile(c.CONFIG, base), repo)
    except (OSError, RuntimeError, ValueError, subprocess.SubprocessError):
        return False
    candidates = [i for i in q["items"] if i.get("kind") == operation.KIND
                  and operation.equivalent(i.get("identity_inputs"), wanted)]
    local = next((i for i in reversed(candidates) if runtime.retained(c, i)), None)
    local = local or next((i for i in reversed(candidates) if i["state"] in admission.ACTIVE), None)
    if not dry:
        links = q.setdefault("review_pr_links", {})
        key = f"{repo}#{pr}"
        previous = links.get(key)
        if local:
            if not previous or (previous["item"], previous["head"], previous["base"]) != (local["id"], head, base):
                links[key] = dict(repo=repo, pr=pr, item=local["id"], head=head, base=base)
            links[key].pop("stale", None)
            local.setdefault("pr_observers", [])
            if key not in local["pr_observers"]:
                local["pr_observers"].append(key)
        elif previous and (previous["head"] != head or previous["base"] != base):
            previous["stale"] = True
    return local is not None


def observe(q):
    """Persist one outbox update per association/terminal/stale transition."""
    items = {i["id"]: i for i in q["items"]}
    for key, link in q.get("review_pr_links", {}).items():
        item = items.get(link["item"])
        if not item:
            continue
        state = "in progress" if item["state"] in admission.ACTIVE else item["state"]
        if link.get("stale"):
            state = "stale; prior coverage only"
        elif item["state"] == "cancelled" and any(
                 q.get("review_requests", {}).get(r.get("supersedes"), {}).get("item") == item["id"]
                 for r in q.get("review_requests", {}).values()):
            state = "superseded"
        elif item.get("scope_adequate"):
            # The clean/findings outcome lives in the retained receipt; publish()
            # replaces this label with it. Never guess "findings" from bookkeeping.
            state = "completed"
        version = [link["item"], link["head"], link["base"], state, item.get("receipt_id")]
        if link.get("version") != version:
            link.update(version=version, state=state)
            q.setdefault("review_pr_outbox", {})[key] = dict(link, attempts=0, pending=True)


def summary(row, result):
    text = (f"{MARKER}\nCodeRabbit CLI via crq; not an independent PASS\n\n"
            f"Provider: coderabbit-cli. Reviewed head: `{row['head']}`.\n"
            f"Base: `{row['base']}`. State: {row['state']}.\n")
    # Only a forge URL generated by this delivery is eligible for publication.
    url = result.get("review_url") or ""
    if url.startswith(f"https://github.com/{row['repo']}/pull/{row['pr']}/"):
        text += f"\n[Inline findings]({url})\n"
    return text


def write_summary(row, body, gh):
    login = findings.authenticated_login(gh)
    endpoint = f"repos/{row['repo']}/issues/{row['pr']}/comments"
    query = (f'.[] | select(.user.login == {json.dumps(login)} and '
             f'((.body // "") | startswith({json.dumps(MARKER)}))) | {{id, body}}')
    out = findings._ok([], findings._call(gh, ["gh", "api", "--paginate", endpoint + "?per_page=100", "--jq", query]))
    found = None
    for line in (out.stdout or "").splitlines():
        value = json.loads(line)
        if isinstance(value, dict) and type(value.get("id")) is int:
            found = value
            break
    if found and found.get("body") == body:
        return
    target = f"repos/{row['repo']}/issues/comments/{found['id']}" if found else endpoint
    argv = ["gh", "api", "--method", "PATCH" if found else "POST", target, "--input", "-"]
    findings._ok(argv, findings._call(gh, argv, input_text=json.dumps(dict(body=body))))


def publish(c, q, gh=None):
    observe(q)
    c.save_queue(q)  # durable before any external write
    gh = gh or findings._gh
    items = {i["id"]: i for i in q["items"]}
    rows = [r for r in q.get("review_pr_outbox", {}).values() if r["pending"] and r["attempts"] < 5
            and r.get("retry_at", 0) <= time.time()]
    for row in sorted(rows, key=lambda r: r.get("attempt_at", ""))[:2]:
        row["attempts"] += 1
        row["attempt_at"] = c.iso()
        try:
            item = items[row["item"]]
            result = row.get("review", {})
            if item.get("scope_adequate") and not row.get("stale") and row["state"] not in ("cancelled", "superseded"):
                doc = runtime.retained(c, item)
                if not doc:
                    raise RuntimeError("retained receipt unavailable")
                row["state"] = doc["outcome"]
                meta = dict(run_id=doc["run_id"], base=row["base"], head=row["head"], local_review=True)
                result = findings.deliver(row["repo"], row["pr"], meta,
                    Path(c.RUNS) / doc["run_id"] / "review.ndjson", gh=gh)
                row["review"] = result
                if result["state"] == "skipped-head":
                    row["state"] = "stale; prior coverage only"
            write_summary(row, summary(row, result), gh)
            row.update(pending=False, error=None)
        except (OSError, RuntimeError, ValueError, KeyError) as exc:
            row["error"] = str(exc)[:300]
            row["retry_at"] = time.time() + min(3600, 60 * 2 ** row["attempts"])
        c.save_queue(q)
