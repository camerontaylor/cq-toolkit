"""Checks for the checked-in B1 publisher oracle vectors.

The vectors are generated by ``publisher_vector_emit_b1.py`` while driving the
real ``review_ledger.GitLedger.publish`` and ``review_ledger.Outbox`` with
injected Git, transport and artifact fakes, so this test proves the committed
file is the current deterministic output and stays public/synthetic. Behavioural
parity is proven by the TypeScript replay of the same file.
"""
import json
import os
from pathlib import Path
import subprocess
import sys
import unittest

import ledger_vector_emit_b1 as base
import publisher_vector_emit_b1 as emitter
import review_ledger as ledger

REQUIRED_PUBLISH_CASES = {
    "idle-outbox",
    "initial-remote-acks",
    "single-enrollment",
    "enrollment-batch-merge",
    "import-batch-merge",
    "import-batch-limit",
    "kind-boundary-separates-batches",
    "finding-event-causal-order",
    "finding-event-missing-review",
    "forked-predecessor",
    "record-over-limit-utf8",
    "push-failure-retries",
    "accepted-then-timeout",
    "concurrent-remote-append",
    "invalid-fetch",
    "ack-missing-after-push",
    "midstream-artifact-failure",
    "partial-ack-before-oversize",
    "partial-ack-before-midstream-artifact",
    "three-push-failures",
}


_DOCUMENT = None


def document():
    global _DOCUMENT
    if _DOCUMENT is None:
        _DOCUMENT = json.loads(emitter.render())
    return _DOCUMENT


def _family(value, name):
    return next(family for family in value["families"] if family["family"] == name)


class PublisherVectorTest(unittest.TestCase):
    def test_checked_in_vectors_are_current(self):
        self.assertEqual(emitter.FIXTURE.read_text(encoding="utf-8"), emitter.render())

    def test_regeneration_is_byte_identical_across_hash_seeds(self):
        path = Path(emitter.__file__).resolve()
        outputs = []
        for seed in ("0", "12345"):
            result = subprocess.run(
                [sys.executable, str(path), "--stdout"],
                check=True,
                capture_output=True,
                env={**os.environ, "PYTHONHASHSEED": seed},
            )
            outputs.append(result.stdout)
        self.assertEqual(outputs[0], outputs[1])
        self.assertEqual(outputs[0].decode("utf-8"), emitter.render())

    def test_rows_are_unique_well_formed_and_public(self):
        value = document()
        self.assertEqual(value["schema"], emitter.SCHEMA)
        families = [family["family"] for family in value["families"]]
        self.assertEqual(len(families), len(set(families)))
        for family in value["families"]:
            names = [case["name"] for case in family["cases"]]
            self.assertEqual(len(names), len(set(names)), family["family"])
            for case in family["cases"]:
                self.assertTrue(case["source"].startswith("review_ledger."), case["source"])
                if not case["expect"]["ok"]:
                    self.assertEqual(case["expect"]["error"], "IntegrityError")
                    self.assertTrue(case["expect"]["message"])
                    if family["family"] == "publish":
                        self.assertIn("value", case["expect"])
                else:
                    self.assertIn("value", case["expect"])
        rendered = emitter.render()
        self.assertNotIn("/home/", rendered)
        self.assertNotIn("/tmp/", rendered)
        self.assertNotIn(os.environ.get("HOME", "\0"), rendered)

    def test_required_publication_behaviours_are_covered(self):
        value = document()
        names = {case["name"] for case in _family(value, "publish")["cases"]}
        self.assertLessEqual(REQUIRED_PUBLISH_CASES, names)
        outbox_names = {case["name"] for case in _family(value, "outbox")["cases"]}
        self.assertLessEqual(
            {"spool-idempotent-replay", "spool-replay-conflict",
             "spool-verifies-artifact", "acknowledge-requires-remote",
             "pending-excludes-ack", "spool-semantic-replay"},
            outbox_names,
        )

    def test_oracle_drives_the_real_publish_and_outbox(self):
        self.assertTrue(issubclass(emitter.OracleLedger, ledger.GitLedger))
        self.assertIs(emitter.OracleLedger.publish, ledger.GitLedger.publish)
        self.assertTrue(issubclass(emitter.RecordingOutbox, ledger.Outbox))
        self.assertIs(emitter.RecordingOutbox.spool, ledger.Outbox.spool)
        self.assertIs(emitter.RecordingOutbox.pending, ledger.Outbox.pending)

    def test_byte_bound_case_separates_utf8_bytes_from_utf16_units(self):
        value = document()
        case = next(case for case in _family(value, "publish")["cases"]
                    if case["name"] == "record-over-limit-utf8")
        record = case["input"]["pending"][0]
        canonical = ledger.canonical(record)
        self.assertGreater(len(canonical), 1024 * 1024)
        self.assertLess(len(canonical.decode("utf-8").encode("utf-16-le")) // 2, 1024 * 1024)
        self.assertEqual(case["expect"]["message"],
                         "ledger record exceeds validation bound")

    def test_accepted_then_timeout_reconciles_without_a_second_push(self):
        value = document()
        case = next(case for case in _family(value, "publish")["cases"]
                    if case["name"] == "accepted-then-timeout")
        value = case["expect"]["value"]
        self.assertEqual(value["push_calls"], 1)
        self.assertEqual(value["fetch_calls"], 2)
        self.assertEqual(len(value["batches"]), 1)
        self.assertEqual(value["pending"], [])

    def test_midstream_failure_keeps_the_accepted_batch(self):
        value = document()
        case = next(case for case in _family(value, "publish")["cases"]
                    if case["name"] == "midstream-artifact-failure")
        value = case["expect"]["value"]
        self.assertEqual(len(value["batches"]), 1)
        self.assertEqual(len(value["acks"]), 1)
        self.assertEqual(len(value["pending"]), 1)

    def test_partial_ack_precedes_the_oversized_refusal(self):
        value = document()
        case = next(case for case in _family(value, "publish")["cases"]
                    if case["name"] == "partial-ack-before-oversize")
        ack_id = case["input"]["ledger"][0]["id"]
        result = case["expect"]["value"]
        self.assertEqual(result["acks"], [ack_id])
        self.assertEqual(result["batches"], [])
        self.assertEqual(len(result["pending"]), 1)
        self.assertEqual(case["expect"]["message"], "ledger record exceeds validation bound")

    def test_partial_ack_precedes_the_midstream_artifact_refusal(self):
        value = document()
        case = next(case for case in _family(value, "publish")["cases"]
                    if case["name"] == "partial-ack-before-midstream-artifact")
        ack_id = case["input"]["ledger"][0]["id"]
        result = case["expect"]["value"]
        self.assertEqual(result["acks"][0], ack_id)
        self.assertEqual(len(result["batches"]), 1)
        self.assertEqual(len(result["pending"]), 1)
        self.assertEqual(case["expect"]["message"], "missing or corrupt retained artifact")

    def test_semantic_replay_is_python_equal_but_not_canonical(self):
        value = document()
        case = next(case for case in _family(value, "outbox")["cases"]
                    if case["name"] == "spool-semantic-replay")
        result = case["expect"]["value"]
        self.assertNotEqual(result["pre_sha256"], result["post_sha256"])
        self.assertEqual(result["pending"][0]["sha256"], result["post_sha256"])

    def test_three_push_failures_retain_the_outbox(self):
        value = document()
        case = next(case for case in _family(value, "publish")["cases"]
                    if case["name"] == "three-push-failures")
        value = case["expect"]["value"]
        self.assertEqual(value["push_calls"], 3)
        self.assertEqual(len(value["pending"]), 1)
        self.assertEqual(case["expect"]["message"],
                         "publication pending; retain scope ownership and reconcile")

    def test_synthetic_artifacts_are_public(self):
        for reference in (emitter.ARTIFACT_OK, emitter.ARTIFACT_BAD):
            self.assertEqual(reference["location"],
                             base.ARTIFACT["location"].replace(
                                 base.ARTIFACT["sha256"], reference["sha256"]))
            self.assertNotIn("/home/", reference["location"])


if __name__ == "__main__":
    unittest.main()
