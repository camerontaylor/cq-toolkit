class FindingIssuesVectorTest(unittest.TestCase):
    def test_checked_in_vectors_are_current(self):
        self.assertEqual(emitter.FIXTURE.read_text(encoding="utf-8"), emitter.render())

    def test_regeneration_is_byte_identical_across_hash_seeds(self):
        path = Path(emitter.__file__).resolve()
        outputs = []
        for seed in ("0", "12345"):
            result = subprocess.run(
                [sys.executable, str(path), "--stdout"],
                check=True,
                capture_output=True,
                env={**os.environ, "PYTHONHASHSEED": seed},
            )
            outputs.append(result.stdout)
        self.assertEqual(outputs[0], outputs[1])

    def test_required_families_and_cases_are_present(self):
        document = json.loads(emitter.FIXTURE.read_text(encoding="utf-8"))
        self.assertEqual(document["schema"], emitter.SCHEMA)
        families = {family["family"]: family for family in document["families"]}
        self.assertEqual(set(families), set(REQUIRED))
        for name, required in REQUIRED.items():
            present = {case["name"] for case in families[name]["cases"]}
            self.assertEqual(present, required, name)

    def test_vectors_are_public_and_synthetic(self):
        text = emitter.FIXTURE.read_text(encoding="utf-8")
        self.assertNotIn("/home/", text)
        self.assertNotIn("/Users/", text)
        self.assertNotIn("-----BEGIN", text)


