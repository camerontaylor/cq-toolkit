"""Checks for the checked-in B1 oracle vectors.

The vectors are generated by ``ledger_vector_emit_b1.py`` from
``review_ledger`` itself, so this test only proves the committed file is the
current deterministic output and stays public/synthetic. Behavioural parity is
proven by ``test/policy/crq/ledger.test.ts`` replaying the same file.
"""
import json
import os
from pathlib import Path
import subprocess
import sys
import unittest

import ledger_vector_emit_b1 as emitter
import review_ledger as ledger


class LedgerVectorTest(unittest.TestCase):
    def test_checked_in_vectors_are_current(self):
        self.assertEqual(emitter.FIXTURE.read_text(encoding="utf-8"), emitter.render())

    def test_regeneration_is_byte_identical_across_hash_seeds(self):
        path = Path(emitter.__file__).resolve()
        outputs = []
        for seed in ("0", "12345"):
            result = subprocess.run(
                [sys.executable, str(path), "--stdout"],
                check=True,
                capture_output=True,
                env={**os.environ, "PYTHONHASHSEED": seed},
            )
            outputs.append(result.stdout)
        self.assertEqual(outputs[0], outputs[1])
        self.assertEqual(outputs[0].decode("utf-8"), emitter.render())

    def test_rows_are_unique_well_formed_and_public(self):
        document = json.loads(emitter.render())
        self.assertEqual(document["schema"], emitter.SCHEMA)
        families = [family["family"] for family in document["families"]]
        self.assertEqual(len(families), len(set(families)))
        for family in document["families"]:
            names = [case["name"] for case in family["cases"]]
            self.assertEqual(len(names), len(set(names)), family["family"])
            for case in family["cases"]:
                self.assertTrue(case["source"].startswith("review_ledger."), case["source"])
                if case["expect"]["ok"]:
                    self.assertIn("value", case["expect"])
                else:
                    self.assertIn(case["expect"]["error"],
                                  ("IntegrityError", "ValueError", "JSONDecodeError",
                                   "UnicodeDecodeError", "KeyError", "TypeError"))
        self.assertNotIn("/home/", emitter.render())
        self.assertNotIn("/tmp/", emitter.render())
        self.assertNotIn(os.environ.get("HOME", "\0"), emitter.render())

    def test_byte_vectors_cover_python_encoding_detection(self):
        cases = {case["name"]: case for case in _family("loads")["cases"]}
        for name in (
            "bytes-utf8-bom",
            "bytes-utf16le-bom",
            "bytes-utf16be-bom",
            "bytes-utf32le-bom",
            "bytes-utf32be-bom",
            "bytes-utf16le-heuristic",
            "bytes-utf16be-heuristic",
            "bytes-utf32le-heuristic",
            "bytes-utf32be-heuristic",
        ):
            self.assertTrue(cases[name]["expect"]["ok"], name)
            self.assertEqual(cases[name]["expect"]["value"], {"雪": "😀", "n": 1}, name)
        self.assertEqual(cases["bytes-invalid-utf8"]["expect"]["error"], "UnicodeDecodeError")
        self.assertEqual(cases["bytes-raw-surrogate-utf8"]["expect"]["error"], "IntegrityError")
        self.assertEqual(cases["bytes-adjacent-surrogates-utf8"]["expect"]["error"],
                         "IntegrityError")
        self.assertEqual(cases["bytes-adjacent-surrogates-utf32"]["expect"]["error"],
                         "IntegrityError")
        self.assertEqual(cases["bytes-utf16-unpaired-surrogate"]["expect"]["error"],
                         "IntegrityError")
        self.assertEqual(cases["bytes-utf16-surrogate-pair"]["expect"]["value"], "😀")
        self.assertEqual(cases["bytes-utf32-scalar"]["expect"]["value"], "😀")
        self.assertEqual(cases["escaped-surrogate-pair"]["expect"]["value"], "😀")

    def test_loads_refusal_order_matches_the_scanner(self):
        cases = {case["name"]: case for case in _family("loads")["cases"]}
        expected = {
            "float-before-trailing-comma": "IntegrityError",
            "syntax-before-nan": "JSONDecodeError",
            "duplicate-before-trailing-comma": "JSONDecodeError",
            "duplicate-at-close": "IntegrityError",
            "duplicate-before-syntax": "JSONDecodeError",
            "duplicate-before-nan": "IntegrityError",
            "nan-before-trailing-comma": "IntegrityError",
            "float-before-syntax": "IntegrityError",
            "float-before-bare-exponent": "IntegrityError",
            "float-before-bare-exponent-sign": "IntegrityError",
            "integer-before-bare-exponent": "JSONDecodeError",
        }
        for name, error in expected.items():
            self.assertEqual(cases[name]["expect"].get("error"), error, name)

    def test_surrogate_string_vectors_preserve_escape_boundaries(self):
        cases = {case["name"]: case for case in _family("loads")["cases"]}
        for name in (
            "escape-high-literal-low",
            "literal-high-escape-low",
            "literal-high-alone",
            "literal-low-alone",
        ):
            self.assertEqual(cases[name]["expect"].get("error"), "IntegrityError", name)
        self.assertEqual(cases["raw-astral"]["expect"]["value"], "😀")
        self.assertEqual(cases["escaped-surrogate-pair"]["expect"]["value"], "😀")

    def test_tampered_id_case_keeps_the_hash_defect(self):
        family = _family("validate")
        case = next(case for case in family["cases"] if case["name"] == "tampered-id")
        value = case["input"]["value"]
        self.assertFalse(case["expect"]["ok"])
        self.assertEqual(case["expect"]["error"], "IntegrityError")
        self.assertNotEqual(value["id"], ledger.digest(
            {key: item for key, item in value.items() if key != "id"}))
        with self.assertRaises(ledger.IntegrityError):
            ledger.validate(value)

    def test_validate_cases_keep_only_their_named_defect(self):
        # A rehash silently repaired the original tampered-id case. Every other
        # validate case must keep a consistent id so the named mutation is the
        # only defect. float-in-integer is exempt because canonical() refuses
        # floats, so its prior id cannot be regenerated.
        for case in _family("validate")["cases"]:
            if case["name"] in ("tampered-id", "float-in-integer"):
                continue
            value = case["input"]["value"]
            self.assertEqual(value["id"], ledger.digest(
                {key: item for key, item in value.items() if key != "id"}), case["name"])

    def test_sequence_members_are_individually_valid(self):
        # Sequence refusals must come from cross-record rules, not an accidental
        # invalid member that would fail earlier for the wrong reason.
        for case in _family("sequence")["cases"]:
            for value in case["input"]["values"]:
                ledger.validate(value)


def _family(name: str):
    document = json.loads(emitter.render())
    return next(family for family in document["families"] if family["family"] == name)


if __name__ == "__main__":
    unittest.main()
