class FindingInboxVectorTest(unittest.TestCase):
    def test_checked_in_vectors_are_current(self):
        self.assertEqual(emitter.FIXTURE.read_text(encoding="utf-8"), emitter.render())

    def test_regeneration_is_byte_identical_across_hash_seeds(self):
        path = Path(emitter.__file__).resolve()
        outputs = []
        for seed in ("0", "12345"):
            result = subprocess.run(
                [sys.executable, str(path), "--stdout"],
                check=True,
                capture_output=True,
                env={**os.environ, "PYTHONHASHSEED": seed},
            )
            outputs.append(result.stdout)
        self.assertEqual(outputs[0], outputs[1])
        self.assertEqual(outputs[0].decode("utf-8"), emitter.render())

    def test_rows_are_unique_well_formed_and_public(self):
        document = json.loads(emitter.render())
        self.assertEqual(document["schema"], emitter.SCHEMA)
        families = [family["family"] for family in document["families"]]
        self.assertEqual(len(families), len(set(families)))
        for family in document["families"]:
            names = [case["name"] for case in family["cases"]]
            self.assertEqual(len(names), len(set(names)), family["family"])
            for case in family["cases"]:
                self.assertTrue(case["source"].startswith("finding_delivery."), case["source"])
                if case["expect"]["ok"]:
                    if (
                        family["family"] == "handoff"
                        and case["input"].get("mode") == "effect"
                    ):
                        self.assertIn("after", case["expect"])
                        self.assertIn("effects", case["expect"])
                        self.assertIn("outbox", case["expect"])
                        self.assertNotIn("value", case["expect"])
                    elif family["family"] in ("ingest", "recover"):
                        self.assertIn("after", case["expect"])
                        self.assertIn("effects", case["expect"])
                        self.assertNotIn("value", case["expect"])
                    else:
                        self.assertIn("value", case["expect"])
                else:
                    self.assertIn(case["expect"]["error"], emitter.ALLOWED_ERRORS)
                for effect in case["expect"].get("effects", []):
                    if effect["kind"] == "write":
                        self.assertNotIn("/", effect["target"])
                        self.assertIn("canonical", effect)
                        self.assertIn("sha256", effect)
        text = emitter.render()
        self.assertNotIn("/home/", text)
        self.assertNotIn("/tmp/", text)
        self.assertNotIn(os.environ.get("HOME", "\0"), text)
        self.assertNotIn(str(Path(emitter.__file__).resolve().parent), text)

    def test_required_cases_are_present(self):
        document = json.loads(emitter.render())
        found = {
            family["family"]: {case["name"] for case in family["cases"]}
            for family in document["families"]
        }
        self.assertEqual(set(found), set(REQUIRED))
        for family, names in REQUIRED.items():
            self.assertTrue(names <= found[family], f"{family}: {sorted(names - found[family])}")

    def test_effect_order_is_bounded_and_lock_scoped(self):
        document = json.loads(emitter.render())
        for family in document["families"]:
            if family["family"] not in ("ingest", "recover"):
                continue
            for case in family["cases"]:
                effects = case["expect"]["effects"]
                open_lock = None
                writes = 0
                for effect in effects:
                    if effect["kind"] == "lock":
                        self.assertIn(effect["phase"], ("enter", "exit"))
                        if effect["phase"] == "enter":
                            self.assertIsNone(open_lock)
                            open_lock = effect["target"]
                        else:
                            self.assertEqual(open_lock, effect["target"])
                            open_lock = None
                    elif effect["kind"] == "write":
                        self.assertIsNotNone(open_lock, case["name"])
                        writes += 1
                self.assertIsNone(open_lock, case["name"])
                if family["family"] == "ingest":
                    self.assertLessEqual(writes, 8)
                else:
                    self.assertLessEqual(writes, 4)

    def test_handoff_effect_lock_stack_and_writes(self):
        document = json.loads(emitter.render())
        handoff = next(
            family for family in document["families"] if family["family"] == "handoff"
        )
        for case in handoff["cases"]:
            if case["input"].get("mode") != "effect":
                continue
            stack = []
            writes = []
            for effect in case["expect"]["effects"]:
                if effect["kind"] == "lock":
                    if effect["phase"] == "enter":
                        stack.append(effect["target"])
                    else:
                        self.assertEqual(stack.pop(), effect["target"], case["name"])
                elif effect["kind"] == "write":
                    self.assertTrue(stack, case["name"])
                    writes.append((effect["target"], tuple(stack)))
            self.assertEqual(stack, [], case["name"])
            name = case["name"]
            if name == "handoff-written":
                self.assertEqual(len(writes), 2, name)
                pending = [write for write in writes if write[1] == ("findings.lock", "outbox.lock")]
                rows = [write for write in writes if write[1] == ("findings.lock",)]
                self.assertEqual(len(pending), 1, name)
                self.assertEqual(len(rows), 1, name)
                self.assertEqual(pending[0][0], case["expect"]["outbox"][0], name)
                self.assertEqual(rows[0][0], case["expect"]["after"][0]["id"], name)
            elif name == "handoff-recovered-after-crash":
                self.assertEqual(len(writes), 1, name)
                self.assertEqual(writes[0][1], ("findings.lock",), name)
                self.assertEqual(writes[0][0], case["expect"]["after"][0]["id"], name)
                self.assertEqual(len(case["expect"]["outbox"]), 1, name)
            else:
                self.assertEqual(writes, [], name)


